"""Tenant-scoped SQLAlchemy repository primitives.

Repositories deliberately leave transaction ownership to the caller. Every
read/write requires an explicit tenant identifier; tenant_id and primary keys
cannot be changed through update().
"""

from collections.abc import Mapping
from typing import Any, Generic, TypeVar
from uuid import UUID

from sqlalchemy import inspect
from sqlalchemy.orm import Session

ModelT = TypeVar("ModelT")


class BaseRepository(Generic[ModelT]):
    """Bounded CRUD operations for ORM models with a tenant_id column."""

    MAX_PAGE_SIZE = 500

    def __init__(self, db: Session, model: type[ModelT]):
        mapper = inspect(model)
        if "tenant_id" not in mapper.columns:
            raise TypeError(f"{model.__name__} is not tenant-scoped")
        self.db = db
        self.model = model

    def get(self, tenant_id: UUID, record_id: UUID) -> ModelT | None:
        return (
            self.db.query(self.model)
            .filter(
                self.model.tenant_id == tenant_id,
                self.model.id == record_id,
            )
            .first()
        )

    def list(
        self,
        tenant_id: UUID,
        *,
        limit: int = 100,
        offset: int = 0,
    ) -> list[ModelT]:
        if not 1 <= limit <= self.MAX_PAGE_SIZE:
            raise ValueError(f"limit must be between 1 and {self.MAX_PAGE_SIZE}")
        if offset < 0:
            raise ValueError("offset must be non-negative")
        return (
            self.db.query(self.model)
            .filter(self.model.tenant_id == tenant_id)
            .order_by(self.model.id)
            .offset(offset)
            .limit(limit)
            .all()
        )

    def create(self, tenant_id: UUID, values: Mapping[str, Any]) -> ModelT:
        payload = dict(values)
        if "id" in payload:
            raise ValueError("primary key is generated by the repository model")
        if "tenant_id" in payload and payload["tenant_id"] != tenant_id:
            raise ValueError("tenant_id cannot differ from repository scope")
        payload["tenant_id"] = tenant_id
        record = self.model(**payload)
        self.db.add(record)
        self.db.flush()
        return record

    def update(
        self,
        tenant_id: UUID,
        record_id: UUID,
        values: Mapping[str, Any],
    ) -> ModelT | None:
        forbidden = {"id", "tenant_id"}
        if forbidden.intersection(values):
            raise ValueError("id and tenant_id are immutable")
        record = self.get(tenant_id, record_id)
        if record is None:
            return None
        columns = {column.key for column in inspect(self.model).columns}
        unknown = set(values) - columns
        if unknown:
            raise ValueError(f"unknown model fields: {', '.join(sorted(unknown))}")
        for key, value in values.items():
            setattr(record, key, value)
        self.db.flush()
        return record

    def delete(self, tenant_id: UUID, record_id: UUID) -> bool:
        record = self.get(tenant_id, record_id)
        if record is None:
            return False
        self.db.delete(record)
        self.db.flush()
        return True
